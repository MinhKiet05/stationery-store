-- Flyway owns only the store schema. No existing public/vector tables are touched.
-- Standard identity, boolean, text, numeric and timestamp types also allow offline H2 verification.
CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(80) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    full_name varchar(120), phone_number varchar(30), address varchar(500),
    role varchar(20) NOT NULL DEFAULT 'CUSTOMER' CHECK (role IN ('ADMIN','CUSTOMER')),
    created_at timestamp(6), is_active boolean DEFAULT true
);
CREATE TABLE vendors (
    vendor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(150) NOT NULL
);
CREATE TABLE product_types (
    product_type_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL, is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_product_type_name UNIQUE(name)
);
CREATE TABLE tags (
    tag_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL
);
CREATE TABLE coupons (
    coupon_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(50) NOT NULL UNIQUE,
    discount_type varchar(20) NOT NULL CHECK (discount_type IN ('PERCENTAGE','FIXED_AMOUNT')),
    discount_value numeric(12,2) NOT NULL, min_order_value numeric(12,2),
    start_date date, end_date date, usage_limit integer, used_count integer DEFAULT 0,
    is_active boolean DEFAULT true
);
CREATE TABLE products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL, handle varchar(100) UNIQUE, url varchar(100),
    available boolean DEFAULT true, description text,
    price numeric(12,2), price_min numeric(12,2), price_max numeric(12,2), compare_at_price numeric(12,2),
    rating_average numeric(3,2) NOT NULL DEFAULT 0, review_count integer NOT NULL DEFAULT 0,
    vendor_id bigint REFERENCES vendors(vendor_id),
    product_type_id bigint REFERENCES product_types(product_type_id), is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE product_variants (
    variant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL, sku varchar(100) UNIQUE, available boolean DEFAULT true,
    price numeric(12,2), compare_at_price numeric(12,2),
    option1 varchar(255), option2 varchar(255), option3 varchar(255),
    stock_quantity integer NOT NULL DEFAULT 0, version bigint,
    product_id bigint NOT NULL REFERENCES products(product_id)
);
CREATE TABLE product_images (
    product_id bigint NOT NULL REFERENCES products(product_id), image_url varchar(500),
    image_position integer NOT NULL, PRIMARY KEY(product_id, image_position)
);
CREATE TABLE product_tags (
    product_id bigint NOT NULL REFERENCES products(product_id), tag_id bigint NOT NULL REFERENCES tags(tag_id),
    PRIMARY KEY(product_id, tag_id)
);
CREATE TABLE carts (
    cart_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES users(user_id), created_at timestamp(6)
);
CREATE TABLE cart_items (
    cart_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    quantity integer NOT NULL, cart_id bigint NOT NULL REFERENCES carts(cart_id)
);
CREATE TABLE orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id), coupon_id bigint REFERENCES coupons(coupon_id),
    order_date timestamp(6), total_amount numeric(12,2), shipping_address varchar(500), contact_phone varchar(30),
    status varchar(30) DEFAULT 'PENDING' CHECK (status IN ('PENDING','PROCESSING','SHIPPED','DELIVERED','CANCELLED','RETURN_PENDING')),
    payment_method varchar(50), is_paid boolean DEFAULT false, discount_amount numeric(12,2), delivered_at timestamp(6)
);
CREATE TABLE order_details (
    order_detail_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(order_id), variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    quantity integer NOT NULL, unit_price numeric(12,2) NOT NULL, sub_total numeric(12,2) NOT NULL
);
CREATE TABLE reviews (
    review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id), product_id bigint NOT NULL REFERENCES products(product_id),
    rating integer NOT NULL, comment text, review_date timestamp(6)
);
CREATE TABLE password_reset_tokens (
    token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id), token_hash varchar(64) NOT NULL UNIQUE,
    expires_at timestamp(6) NOT NULL, used boolean NOT NULL DEFAULT false, created_at timestamp(6) NOT NULL
);
CREATE TABLE return_requests (
    return_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders(order_id), user_id bigint NOT NULL REFERENCES users(user_id),
    reason varchar(1000) NOT NULL, evidence_images text,
    status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','COMPLETED')),
    created_at timestamp(6) NOT NULL, processed_at timestamp(6), admin_note varchar(1000)
);
CREATE TABLE return_request_items (
    return_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id bigint NOT NULL REFERENCES return_requests(return_id),
    order_detail_id bigint NOT NULL REFERENCES order_details(order_detail_id), quantity integer NOT NULL
);
CREATE TABLE user_tracking_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(user_id), product_id bigint NOT NULL REFERENCES products(product_id),
    event_type varchar(30) NOT NULL CHECK (event_type IN ('VIEW_PRODUCT','ADD_TO_CART','PURCHASE')),
    created_at timestamp(6) NOT NULL
);

-- FK lookup and history indexes; no vector index is created on a 3072-dimensional column.
CREATE INDEX ix_products_vendor ON products(vendor_id);
CREATE INDEX ix_products_type ON products(product_type_id);
CREATE INDEX ix_product_variants_product ON product_variants(product_id);
CREATE INDEX ix_product_tags_tag ON product_tags(tag_id);
CREATE INDEX ix_cart_items_cart ON cart_items(cart_id);
CREATE INDEX ix_cart_items_variant ON cart_items(variant_id);
CREATE INDEX ix_orders_user_date ON orders(user_id, order_date DESC);
CREATE INDEX ix_orders_coupon ON orders(coupon_id);
CREATE INDEX ix_order_details_order ON order_details(order_id);
CREATE INDEX ix_order_details_variant ON order_details(variant_id);
CREATE INDEX ix_reviews_product ON reviews(product_id);
CREATE INDEX ix_reviews_user ON reviews(user_id);
CREATE INDEX ix_reset_tokens_user ON password_reset_tokens(user_id);
CREATE INDEX ix_returns_order ON return_requests(order_id);
CREATE INDEX ix_returns_user ON return_requests(user_id);
CREATE INDEX ix_return_items_return ON return_request_items(return_id);
CREATE INDEX ix_return_items_detail ON return_request_items(order_detail_id);
CREATE INDEX ix_tracking_user_time ON user_tracking_events(user_id, created_at DESC);
CREATE INDEX ix_tracking_cooldown ON user_tracking_events(user_id, product_id, event_type, created_at DESC);
CREATE INDEX ix_tracking_product ON user_tracking_events(product_id);
